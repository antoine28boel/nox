import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:nox/assistant/ha_dashboard.dart';
import 'package:nox/assistant/home.dart';
import 'package:nox/assistant/panel_style.dart';

void main() {
  test('the dashboards list starts with the default one', () {
    final list = parseDashboards([
      {'url_path': 'maison', 'title': 'Maison', 'mode': 'storage'},
      {'url_path': 'map', 'title': 'Carte'},
      {'url_path': 'energy', 'title': 'Énergie', 'mode': 'built-in'},
    ]);
    expect([for (final d in list) d.urlPath], ['lovelace', 'maison', 'map']);
    expect(list.first.title, 'Aperçu');
  });

  test('a masonry view gives one group per titled card', () {
    final views = parseDashboardConfig({
      'views': [
        {
          'title': 'Salon',
          'badges': ['sensor.temperature_salon'],
          'cards': [
            {
              'type': 'entities',
              'title': 'Lumières',
              'entities': [
                'light.plafond',
                {'entity': 'light.lampe', 'name': 'Lampe'},
                {'type': 'divider'},
              ],
            },
            {
              'type': 'vertical-stack',
              'cards': [
                {'type': 'tile', 'entity': 'cover.volet'},
                {
                  'type': 'conditional',
                  'conditions': [
                    {'entity': 'sun.sun', 'state': 'below_horizon'},
                  ],
                  'card': {'type': 'button', 'entity': 'scene.soiree'},
                },
              ],
            },
            {'type': 'markdown', 'content': 'light.pas_une_entite'},
          ],
        },
        {
          'strategy': {'type': 'original-states'},
        },
      ],
    });
    expect(views, hasLength(1));
    final groups = views.single.groups;
    expect([for (final g in groups) g.title], [null, 'Lumières', null]);
    expect([for (final e in groups[1].entities) e.id], ['light.plafond', 'light.lampe']);
    expect(groups[1].entities[1].name, 'Lampe');
    expect([for (final e in groups[2].entities) e.id], ['cover.volet', 'scene.soiree']);
  });

  test('a sections view uses section titles and headings', () {
    final views = parseDashboardConfig({
      'views': [
        {
          'path': 'etage',
          'sections': [
            {
              'cards': [
                {'type': 'heading', 'heading': 'Chambre'},
                {'type': 'tile', 'entity': 'light.chambre'},
                {'type': 'tile', 'entity': 'light.chambre'},
                {'type': 'heading', 'heading': 'Bureau'},
                {'type': 'tile', 'entity': 'switch.bureau'},
              ],
            },
            {
              'title': 'Climat',
              'cards': [
                {'type': 'thermostat', 'entity': 'climate.etage'},
              ],
            },
          ],
        },
      ],
    });
    final view = views.single;
    expect(view.title, 'etage');
    expect([for (final g in view.groups) g.title], ['Chambre', 'Bureau', 'Climat']);
    expect(view.groups.first.entities, hasLength(1));
  });

  test('a dashboard generated by Home Assistant has no views', () {
    expect(
      parseDashboardConfig({
        'strategy': {'type': 'original-states'},
      }),
      isEmpty,
    );
    expect(parseDashboardConfig(null), isEmpty);
  });

  test('sensors are read with their unit', () {
    final byId = parseEntities([
      {
        'entity_id': 'sensor.temperature_salon',
        'state': '19.46',
        'attributes': {'unit_of_measurement': '°C', 'device_class': 'temperature'},
      },
      {
        'entity_id': 'binary_sensor.porte',
        'state': 'on',
        'attributes': {'device_class': 'door', 'friendly_name': 'Porte'},
      },
    ]);
    expect(deviceLabel(byId['sensor.temperature_salon']!), '19,5 °C');
    expect(deviceLabel(byId['binary_sensor.porte']!), 'Ouvert');
    expect(byId['binary_sensor.porte']!.named('Entrée').name, 'Entrée');
  });

  test('the panel remembers folded sections and the dashboard', () {
    final store = <String, String>{};
    final memory = PanelMemory(read: (k) => store[k], write: (k, v) => store[k] = v);
    memory.toggle('tasks:todo.courses');
    memory.toggle('agenda:2026-11-10');
    memory.dashboard = 'maison';
    final again = PanelMemory(read: (k) => store[k], write: (k, v) => store[k] = v);
    expect(again.isCollapsed('tasks:todo.courses'), isTrue);
    expect(again.dashboard, 'maison');
    again.prune('agenda:2', (k) => k.compareTo('agenda:2026-11-17') >= 0);
    expect(again.isCollapsed('agenda:2026-11-10'), isFalse);
    again.toggle('tasks:todo.courses');
    expect(PanelMemory(read: (k) => store[k]).isCollapsed('tasks:todo.courses'), isFalse);
  });

  testWidgets('a section folds on a tap on its title', (tester) async {
    var collapsed = false;
    await tester.pumpWidget(
      MaterialApp(
        home: Scaffold(
          body: StatefulBuilder(
            builder: (context, setState) => PanelSection(
              title: 'Courses',
              collapsed: collapsed,
              count: 2,
              onToggle: () => setState(() => collapsed = !collapsed),
              children: const [Text('Pain'), Text('Lait')],
            ),
          ),
        ),
      ),
    );
    expect(find.text('Pain'), findsOneWidget);
    await tester.tap(find.text('COURSES'));
    await tester.pump();
    expect(find.text('Pain'), findsNothing);
    expect(find.text('COURSES  (2)'), findsOneWidget);
  });
}
