// Home Assistant dashboards (Lovelace): which ones exist, and which devices
// each view shows, grouped as on the dashboard.
//
// Pure Dart, so it can be tested without a network.

/// A dashboard the user can pick for the "Maison" tab.
class HaDashboardInfo {
  const HaDashboardInfo({required this.urlPath, required this.title});

  /// Path used by Home Assistant ("lovelace" for the default one).
  final String urlPath;
  final String title;
}

/// One device on a dashboard, with the name the dashboard gives it, if any.
class DashboardEntity {
  const DashboardEntity(this.id, [this.name]);

  final String id;
  final String? name;
}

/// A titled group of devices (a card, a section…).
class DashboardGroup {
  const DashboardGroup({this.title, required this.entities});

  final String? title;
  final List<DashboardEntity> entities;
}

/// A view (page) of a dashboard.
class DashboardView {
  const DashboardView({required this.title, required this.groups});

  final String title;
  final List<DashboardGroup> groups;
}

String? _string(Object? v) => v is String && v.trim().isNotEmpty ? v.trim() : null;

/// Reads the answer of `lovelace/dashboards/list`; the default dashboard,
/// which is not in that list, comes first.
List<HaDashboardInfo> parseDashboards(Object? json) {
  final dashboards = [const HaDashboardInfo(urlPath: 'lovelace', title: 'Aperçu')];
  if (json is! List) return dashboards;
  for (final d in json) {
    if (d is! Map) continue;
    final path = _string(d['url_path']);
    if (path == null || path == 'lovelace') continue;
    // Map, logbook, energy… are not dashboards of devices.
    if (d['mode'] != null && d['mode'] != 'storage' && d['mode'] != 'yaml') continue;
    dashboards.add(HaDashboardInfo(urlPath: path, title: _string(d['title']) ?? path));
  }
  return dashboards;
}

/// Reads the answer of `lovelace/config`. Empty when the dashboard is
/// generated by Home Assistant (a "strategy"): Nox then shows every device.
List<DashboardView> parseDashboardConfig(Object? config) {
  final views = <DashboardView>[];
  if (config is! Map) return views;
  final rawViews = config['views'];
  if (rawViews is! List) return views;
  var index = 0;
  for (final v in rawViews) {
    index++;
    if (v is! Map || v['strategy'] != null) continue;
    final title = _string(v['title']) ?? _string(v['path']) ?? 'Vue $index';
    final groups = <DashboardGroup>[];

    final badges = _collect(v['badges']);
    if (badges.isNotEmpty) groups.add(DashboardGroup(entities: badges));

    final sections = v['sections'];
    if (sections is List) {
      for (final s in sections) {
        if (s is! Map) continue;
        _addCards(groups, s['cards'], _string(s['title']));
      }
    }
    _addCards(groups, v['cards'], null);

    final kept = [
      for (final g in groups)
        if (g.entities.isNotEmpty) g,
    ];
    if (kept.isNotEmpty) views.add(DashboardView(title: title, groups: kept));
  }
  return views;
}

/// Adds the cards of a view or a section: each top-level card is a group,
/// a "heading" card titles the cards after it.
void _addCards(List<DashboardGroup> groups, Object? cards, String? title) {
  if (cards is! List) return;
  var heading = title;
  var current = <DashboardEntity>[];
  void flush() {
    if (current.isNotEmpty) groups.add(DashboardGroup(title: heading, entities: current));
    current = <DashboardEntity>[];
  }

  for (final card in cards) {
    if (card is! Map) continue;
    if (card['type'] == 'heading') {
      flush();
      heading = _string(card['heading']) ?? heading;
      current.addAll(_collect(card['badges']));
      continue;
    }
    final own = _string(card['title']);
    if (own != null) {
      flush();
      groups.add(DashboardGroup(title: own, entities: _dedupe(_collect(card))));
    } else {
      current.addAll(_collect(card));
    }
  }
  flush();
  for (var i = 0; i < groups.length; i++) {
    groups[i] = DashboardGroup(title: groups[i].title, entities: _dedupe(groups[i].entities));
  }
}

/// Every entity a card (or list of cards, badges…) shows, in order.
List<DashboardEntity> _collect(Object? node) {
  final found = <DashboardEntity>[];
  void walk(Object? n) {
    if (n is String) {
      if (_isEntityId(n)) found.add(DashboardEntity(n));
    } else if (n is List) {
      n.forEach(walk);
    } else if (n is Map) {
      final entity = _string(n['entity']);
      if (entity != null && _isEntityId(entity)) {
        found.add(DashboardEntity(entity, _string(n['name'])));
      }
      walk(n['entities']);
      walk(n['card']);
      walk(n['cards']);
      walk(n['chips']);
      walk(n['badges']);
    }
  }

  walk(node);
  return found;
}

final _entityId = RegExp(r'^[a-z_]+\.[a-z0-9_]+$');
bool _isEntityId(String s) => _entityId.hasMatch(s);

List<DashboardEntity> _dedupe(List<DashboardEntity> entities) {
  final seen = <String>{};
  return [
    for (final e in entities)
      if (seen.add(e.id)) e,
  ];
}
